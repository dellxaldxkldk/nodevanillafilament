#include <string>
#include <vector>

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void max_of_two() {
    int a = 33, b = 57;
    int m = (a > b) ? a : b;
    (void)m;
}

void count_spaces() {
    std::string text = "a b  c   d";
    int spaces = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == ' ') spaces += 1;
    }
    (void)spaces;
}

void balanced_sum() {
    int left = 1 + 2 + 3;
    int right = 4 + 2;
    bool balanced = (left == right);
    (void)balanced;
}

extern "C" int gentle_fjord();
extern "C" void subtle_grove();
extern "C" void sable_lantern();
extern "C" void gentle_thorn();
extern "C" void golden_boulder();

int main() {
    text_contains();
    max_of_two();
    count_spaces();
    balanced_sum();
    subtle_grove();
    sable_lantern();
    gentle_thorn();
    golden_boulder();
    return gentle_fjord();
}
